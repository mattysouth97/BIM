/**
 * FZK Haus (Karlsruhe) as energy-engine input — the Clinic's and
 * Schependomlaan's sibling, and the first of the three with no placeholders
 * at all: every envelope figure below is either read from the committed
 * manifest or from a `ThermalTransmittance` / `IfcMaterialLayer` the file
 * states directly on the element.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  WHAT MAKES THIS FILE DIFFERENT FROM ITS TWO SIBLINGS
 *
 *  The Clinic states no U-value anywhere (zero `IfcThermalTransmittanceMeasure`).
 *  Schependomlaan states 97 of them and every one is a documented zero — an
 *  authoring artefact, not a value, so its U-values are SOLVED from layer
 *  sets instead. FZK Haus states 33 — one per wall, window, door and slab —
 *  and every one is a real, non-zero, plausible number (exterior wall 0.4,
 *  window 1.4, roof 0.3 W/m²K). This file therefore does the opposite of
 *  Schependomlaan's: the STATED per-element U is the primary source, and the
 *  layer-solved figure (`FZK_HAUS_WALL_ASSEMBLY_SOLVED`) is the disclosed
 *  cross-check, not the other way round. See `A-STATED-U-PRIMARY`.
 *
 *  The one place that reverses again is the ground slab. `Bodenplatte`
 *  states ThermalTransmittance 0.4 — an ordinary air-to-air U — and using it
 *  as the ground-facing U would repeat the Clinic's own headline defect (a
 *  slab on grade has no air-to-air U; ISO 13370 applies, not ISO 6946). So
 *  the ground floor is the one element where the stated 0.4 is DISCLOSED but
 *  NOT used, and `slabOnGroundUValue` runs instead on the slab's own stated
 *  layer (0.2 m reinforced concrete, no insulation board at all). See
 *  `A-GROUND-STATED-U-NOT-AIR-TO-AIR`.
 * ══════════════════════════════════════════════════════════════════════════
 *
 * Same discipline as `bs-medical-dental-clinic-energy.ts`: four exports
 * (`FZK_HAUS_RECIPE`, `FZK_HAUS_MATERIALS`, `FZK_HAUS_MEASURED_ENVELOPE`,
 * `FZK_HAUS_ASSUMPTIONS`), no `_PENDING_MEASUREMENTS` — there is nothing
 * pending.
 *
 * Sources:
 *   - `public/reference-buildings/fzk-haus/manifest.json`, generated by
 *     `scripts/build-reference-building.mjs` (`FZK_HAUS` config) from KIT/IAI's
 *     `AC20-FZK-Haus.ifc` (unrestricted use, attribution required — see the
 *     config comment and `docs/04_Agent-Handoffs/2026-09-06-gallery-consistency-visuals-brief.md`).
 *   - `public/reference-buildings/fzk-haus/spaces.json`, 7 IfcSpace rows.
 *   - `public/reference-buildings/fzk-haus/openings.json`, 13 opening rows.
 */


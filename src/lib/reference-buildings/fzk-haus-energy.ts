/**
 * ONE whole-building ratio, on all four cardinal keys — NOT the four
 * measured per-sector ratios, even though this building's glazing genuinely
 * is measured per sector. `heat-loss.ts`'s `meanWindowToWallRatio` weights
 * by `walls[].surfaceArea`, which is NET opaque wall, while each per-sector
 * ratio's own denominator is that sector's GROSS wall (wall+glazing+door) —
 * they do not cancel, so handing the four real ratios in would move the
 * engine's answer for no reason connected to what was actually measured.
 * Measured on this building (bim-83 found the same shape on the Duplex,
 * where the effect is 10x larger — see A-WWR-ENGINE-MEAN):
 *
 *   weighted-by-net-wall mean   0.141506   (uniform: 0.141585)
 *   window area                22.996 m²  against a measured 23.6 m²
 *
 * The gap is tiny here (FZK Haus's four sector ratios span 0.125-0.190,
 * against the Duplex's 0.10-0.37), but the mechanism is identical and the
 * fix is the same: one ratio, against gross, is the only figure that
 * reproduces the building's own measured aperture exactly — see
 * `A-WWR-ENGINE-MEAN`. The real per-sector figures stay available in
 * `FZK_HAUS_WALL_BY_SECTOR_SQM` / `_GLAZING_BY_SECTOR_SQM` / `_DOOR_BY_SECTOR_SQM`
 * for the legend, which is the only current consumer that can say anything
 * with four different numbers.
 */

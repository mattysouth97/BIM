// Calibrated visual PBR catalog. Thermal λ/U live in energy-standards;
// these numbers are reflectance, roughness and real-world scale only.

import type { VisualMaterialId, VisualMaterialSpec } from "./types";
import { MATERIAL_ONTOLOGY } from "./material-ontology";
import { clampAlbedoHex, clampIor, clampMetalness, clampRoughness } from "./pbr-standards";

function spec(
  partial: Omit<VisualMaterialSpec, "nameKo" | "nameEn">,
): VisualMaterialSpec {
  const node = MATERIAL_ONTOLOGY.find((n) => n.id === partial.id);
  if (!node) throw new Error(`Library entry missing ontology node: ${partial.id}`);
  const metallic = partial.metalness >= 0.5;
  return {
    ...partial,
    nameKo: node.nameKo,
    nameEn: node.nameEn,
    albedo: clampAlbedoHex(partial.albedo, metallic),
    roughness: clampRoughness(partial.roughness),
    metalness: clampMetalness(partial.metalness),
    ior: clampIor(partial.ior),
  };
}


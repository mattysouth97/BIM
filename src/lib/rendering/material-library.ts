const BY_ID = new Map(MATERIAL_LIBRARY.map((s) => [s.id, s]));

export function getVisualMaterial(id: VisualMaterialId): VisualMaterialSpec {
  const spec = BY_ID.get(id);
  if (!spec) throw new Error(`Unknown visual material: ${id}`);
  return spec;
}

export function tryGetVisualMaterial(id: string | undefined): VisualMaterialSpec | null {
  if (!id) return null;
  return BY_ID.get(id as VisualMaterialId) ?? null;
}
